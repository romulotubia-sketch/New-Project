/**
 * Returns the Hero Level required to unlock a given skill index.
 * Lv. 1 (Default): Normal Skills 0 & 1 + Ultimate Skill 0.
 * Lv. 2: Normal Skill 2
 * Lv. 3: Normal Skill 3
 * Lv. 4: Ultimate Skill 1
 * Lv. 5: Normal Skill 4
 * Lv. 6: Ultimate Skill 2
 */
export function getSkillRequiredHeroLevel(kind: 'normal' | 'ultimate', index: number): number {
  if (kind === 'normal') {
    if (index <= 1) return 1;
    if (index === 2) return 2;
    if (index === 3) return 3;
    return 5;
  }
  if (index <= 0) return 1;
  if (index === 1) return 4;
  return 6;
}

export function getSkillUnlockedAtHeroLevel(
  hero: CharacterConfig,
  level: number
): { kind: 'normal' | 'ultimate'; index: number; skill: Skill } | null {
  if (level === 2 && hero.normalSkills[2]) return { kind: 'normal', index: 2, skill: hero.normalSkills[2] };
  if (level === 3 && hero.normalSkills[3]) return { kind: 'normal', index: 3, skill: hero.normalSkills[3] };
  if (level === 4 && hero.ultimateSkills[1]) return { kind: 'ultimate', index: 1, skill: hero.ultimateSkills[1] };
  if (level === 5 && hero.normalSkills[4]) return { kind: 'normal', index: 4, skill: hero.normalSkills[4] };
  if (level === 6 && hero.ultimateSkills[2]) return { kind: 'ultimate', index: 2, skill: hero.ultimateSkills[2] };
  return null;
}

